"""Shared HTTP utilities and standard browser headers.

Modern browser headers matching desktop Chrome on Windows to ensure compatibility
with web endpoints. Referred to exclusively as standard browser headers.
"""

STANDARD_BROWSER_HEADERS: dict[str, str] = {
    "User-Agent": (
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
        "AppleWebKit/537.36 (KHTML, like Gecko) "
        "Chrome/124.0.0.0 Safari/537.36"
    ),
    "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,image/avif,image/webp,*/*;q=0.8",
    "Accept-Language": "en-US,en;q=0.9,fa;q=0.8",
    "Sec-Ch-Ua": '"Chromium";v="124", "Google Chrome";v="124", "Not-A.Brand";v="99"',
    "Sec-Ch-Ua-Mobile": "?0",
    "Sec-Ch-Ua-Platform": '"Windows"',
    "Sec-Fetch-Dest": "document",
    "Sec-Fetch-Mode": "navigate",
    "Sec-Fetch-Site": "none",
    "Sec-Fetch-User": "?1",
    "Upgrade-Insecure-Requests": "1",
}


def get_standard_browser_headers(extra: dict[str, str] | None = None) -> dict[str, str]:
    """Return a copy of standard browser headers with optional extras merged."""
    headers = dict(STANDARD_BROWSER_HEADERS)
    if extra:
        headers.update(extra)
    return headers
